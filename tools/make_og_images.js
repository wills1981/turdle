// Renders the weekday link-preview images (icons/og-<day>.png, plus icons/og-image.png = Monday)
// and writes the weekday share pages (<day>/index.html) that point crawlers at them.
// The game's share link goes to the puzzle's weekday page, which redirects straight to the game.
//
//   node tools/make_og_images.js
//
// Needs playwright-core (npm i playwright-core) and a Chromium: set CHROME to its executable,
// or it uses Playwright's cached Chrome for Testing on macOS.
const { chromium } = require('playwright-core');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://wills1981.github.io/turdle/';
const VERSION = 3; // bump to make crawlers refetch the images
const DAYS = [ // Monday first, as the user listed them
  ['mon', 'Monday', 'BUMS'], ['tue', 'Tuesday', 'TIT'], ['wed', 'Wednesday', 'FARTY'],
  ['thu', 'Thursday', 'GONAD'], ['fri', 'Friday', 'ARSE'], ['sat', 'Saturday', 'TWAT'], ['sun', 'Sunday', 'BALLS'],
];

function imageHtml(word) {
  const svg = fs.readFileSync(path.join(ROOT, 'icons/icon.svg'), 'utf8').replace('<svg ', '<svg width="300" height="300" ');
  const tiles = [...word].map(l => `<div class="t">${l}</div>`).join('');
  return `<html><head>
    <link href="https://fonts.googleapis.com/css2?family=Fredoka:wght@600;700&family=Nunito:wght@800&display=swap" rel="stylesheet">
    <style>
      body{margin:0;width:1200px;height:630px;background:#fdf6ec;font-family:Fredoka,sans-serif;display:flex;align-items:center;gap:64px;padding:0 90px;box-sizing:border-box;color:#3b2a1e}
      .logo{border-radius:64px;overflow:hidden;box-shadow:0 14px 0 #9c3f14;flex:none;width:300px;height:300px}
      h1{font-size:132px;margin:0;line-height:1}
      p{font-family:Nunito,sans-serif;font-weight:800;font-size:34px;color:#a4593a;margin:14px 0 34px;text-transform:uppercase;letter-spacing:1px}
      .row{display:flex;gap:14px}
      /* every tile in the "correct letter" colour (.tile-match) */
      .t{width:84px;height:84px;border-radius:20px;display:flex;align-items:center;justify-content:center;font-size:48px;font-weight:700;background:#1aa58a;color:#fff;border:3px solid #128069;border-bottom-width:8px}
    </style></head><body>
    <div class="logo">${svg}</div>
    <div><h1>Turdle!</h1><p>Daily word shift puzzle</p><div class="row">${tiles}</div></div>
  </body></html>`;
}

function sharePage(day, word) {
  const img = `${SITE}icons/og-${day}.png?v=${VERSION}`;
  return `<!DOCTYPE html>
<!-- Generated by tools/make_og_images.js: edit that, not this. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Turdle! - Daily Puzzle Game</title>
  <meta name="description" content="A silly daily word-ladder puzzle by Rob Wills &amp; AI!">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Turdle!">
  <meta property="og:title" content="Turdle! - Daily Puzzle Game">
  <meta property="og:description" content="A silly daily word-ladder puzzle by Rob Wills &amp; AI!">
  <meta property="og:url" content="${SITE}${day}/">
  <meta property="og:image" content="${img}">
  <meta property="og:image:type" content="image/png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="Turdle! logo with letter tiles spelling ${word}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="${img}">
  <meta http-equiv="refresh" content="0;url=../">
  <script>location.replace('../' + location.search);</script>
</head>
<body><a href="../">Play Turdle!</a></body>
</html>
`;
}

(async () => {
  const exe = process.env.CHROME || process.env.HOME +
    '/Library/Caches/ms-playwright/chromium-1228/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
  const browser = await chromium.launch({ executablePath: exe });
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
  for (const [day, , word] of DAYS) {
    await page.setContent(imageHtml(word));
    await page.waitForLoadState('networkidle');
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: path.join(ROOT, `icons/og-${day}.png`) });
    if (day === 'mon') fs.copyFileSync(path.join(ROOT, 'icons/og-mon.png'), path.join(ROOT, 'icons/og-image.png'));
    fs.mkdirSync(path.join(ROOT, day), { recursive: true });
    fs.writeFileSync(path.join(ROOT, day, 'index.html'), sharePage(day, word));
    console.log(`${day}: ${word}`);
  }
  await browser.close();
})();
